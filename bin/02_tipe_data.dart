void main() {
  // Deklarasi variabel dengan berbagai tipe data dasar di Dart
  int angka = 10;
  double desimal = 3.14;
  String teks = "Halo, dunia!";
  bool benar = true;

  // Menampilkan nilai variabel sesuai contoh pada Modul 1 Halaman 3
  print(angka);
  print(desimal);
  print(teks);
  print(benar);

  // Contoh tambahan tipe data var (tipe inferensi otomatis)
  var variabelVar = "Dart otomatis mendeteksi tipe data ini sebagai String";
  print("Tipe var: $variabelVar");
}

